fn white(temperature: f64) -> Result<[f64; 3], RasterInputError> {
    if !temperature.is_finite() || !(1000.0..=12000.0).contains(&temperature) {
        return Err(RasterInputError::UnsupportedConversion);
    }
    let position = (temperature - 1000.0) / 25.0;
    let base = (position.floor() as usize).saturating_sub(1).min(WHITE_RESPONSE.len().saturating_sub(4));
    let fraction = position - base as f64;
    let mut result = [0.0; 3];
    for (channel, value) in result.iter_mut().enumerate() {
        for k in 0..4_usize {
            let row = WHITE_RESPONSE.get(base.checked_add(k).ok_or(RasterInputError::InvalidBounds)?).ok_or(RasterInputError::InvalidBounds)?;
            let sample = *row.get(channel).ok_or(RasterInputError::InvalidBounds)?;
            if !sample.is_finite() || sample == 0.0 {
                return Err(RasterInputError::UnsupportedConversion);
            }
            let mut weight = 1.0;
            for l in 0..4_usize {
                if l != k {
                    weight *= (fraction - l as f64) / (k as f64 - l as f64);
                }
            }
            *value += weight / sample;
        }
        if !value.is_finite() || *value == 0.0 {
            return Err(RasterInputError::UnsupportedConversion);
        }
    }
    Ok(result)
}
pub(super) fn gains(original: f64, intended: f64) -> Result<[f64; 3], RasterInputError> {
    let original = white(original)?;
    let intended = white(intended)?;
    let mut result = [0.0; 3];
    for ((value, source), target) in result.iter_mut().zip(original).zip(intended) {
        *value = source / target;
        if !value.is_finite() || value.abs() > 256.0 {
            return Err(RasterInputError::UnsupportedConversion);
        }
        *value = f64::from(*value as f32);
    }
    Ok(result)
}
