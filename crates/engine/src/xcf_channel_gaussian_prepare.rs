//! Explicit private stored-channel -> numerical Gaussian preparation.
//!
//! No default Load, channel write, Bake, renderer or source qualification is
//! supplied. The original prepare path checks blob/node correspondence only.
//! The additive opaque IO-owner path also verifies decoded original native
//! channel/mask planes; neither proves numerical filter appearance or Bake.
//! Caller working-format evidence remains separate from parent image encoding.
//! Original 96x80 mask/opaque records stay in the frozen source, unconsumed.
//!
//! The complete lower-only resident/work envelope is conservatively reserved
//! before discovery/copies. This is admission, not actual allocation or RSS.
//! Model/payload inspector limits and the Gaussian stages share the remaining
//! local ledger. Caller-owned evidence/container backing beyond exposed slices
//! must also be charged by its enclosing owner. No reservation is refunded.
use crate::{
    DocumentSnapshot, EngineError, Result, Session,
    channel_cmds::ChannelView,
    xcf_channel_consumer::{self, ChannelConsumer, SourceBinding},
};
use photocraft_compose::{
    gimp_channel_gaussian_candidate as gaussian,
    gimp_composite::{CompositionError, Result as ComposeResult},
    gimp_render::PreparationBudget,
};
use photocraft_doc::{
    LayerId,
    item_identity::{ChannelId, ItemRef},
    xcf_filters::FilterNode,
};
use photocraft_raster::{Interrupt, Surface};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};

// Prospective index of the closed one-tile Gaussian candidate. Its returned
// requirement is checked against this reservation before retaining the stage.
const DERIVED_INDEX_RESERVATION: u64 = 32 * 256;

pub use gaussian::Limits;
/// Required caller observation, not a credential generated by this facade.
/// A source fingerprint plus native format/space descriptors does not itself
/// prove original-plane correspondence or full filter/mask appearance.
pub struct WorkingDomainEvidence<'a> {
    pub domain: gaussian::NativeDomain,
    pub native_format: &'a str,
    pub native_space: &'a str,
    pub source_sha256: &'a str,
}
pub struct SourceEvidence<'a> {
    pub original_bytes: &'a [u8],
    pub original_node: &'a FilterNode,
    pub working: WorkingDomainEvidence<'a>,
}
enum PreparationInput<'e, 's, 'b, 't> {
    Metadata(SourceEvidence<'e>),
    Correspondence { owner: &'e photocraft_io::AssembledStoredChannel<'s, 'b, 't>, working: WorkingDomainEvidence<'e> },
    Selected { owner: &'e photocraft_io::AssembledStoredChannel<'s, 'b, 't>, working: WorkingDomainEvidence<'e> },
}
impl PreparationInput<'_, '_, '_, '_> {
    fn original_bytes(&self) -> &[u8] {
        match self {
            Self::Metadata(evidence) => evidence.original_bytes,
            Self::Correspondence { owner, .. } | Self::Selected { owner, .. } => owner.original_bytes(),
        }
    }
}
/// Describes verification already performed on the retained immutable snapshot.
/// This is not renderer/source admission or any persisted editing authority.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SourceCorrespondence {
    MetadataOnly,
    DecodedOriginalNativePlanes,
    SelectedDecodedOriginalNativePlanes,
}
#[derive(Clone, Copy, Debug)]
pub struct Requirements {
    /// Full conservative envelope lease, not the measured live byte count.
    pub admitted_resident_bytes: u64,
    pub admitted_work_units: u64,
    pub source_raster_bytes: u64,
    pub source_model_bytes: u64,
    pub source_payload_bytes: u64,
    pub source_and_view_bytes: u64,
    /// Additional entire decoded IO owner, including its retained reservations.
    pub correspondence_owner_bytes: u64,
    pub correspondence_owner_index_bytes: u64,
    pub correspondence_verification_work: u64,
    /// Conservative pre-census receipt bound, not CPU time or refunded work.
    pub correspondence_prepaid_work_units: u64,
    pub selected_namespace_work_units: u64,
    pub index_envelope_bytes: u64,
    pub preparation_work_units: u64,
    pub derived: gaussian::Requirements,
}
struct Work {
    used: AtomicU64,
    exceeded: AtomicBool,
    limit: u64,
}
impl Work {
    fn charge(&self, units: u64) -> Result<()> {
        self.used.try_update(Ordering::Relaxed, Ordering::Relaxed, |n| n.checked_add(units).filter(|n| *n <= self.limit)).map_err(|_| {
            self.exceeded.store(true, Ordering::Relaxed);
            bad("channel preparation work limit")
        })?;
        Ok(())
    }
    fn remaining(&self) -> u64 {
        self.limit.saturating_sub(self.used.load(Ordering::Relaxed))
    }
}
/// Proof work is debited before source census. IO callbacks spend this receipt
/// only; token polls still debit Work, and unused quota is never refunded.
struct PrepaidProofWork {
    remaining: u64,
}
impl PrepaidProofWork {
    fn reserve(work: &Work, units: u64) -> Result<Self> {
        work.charge(units)?;
        Ok(Self { remaining: units })
    }
    fn consume(&mut self, units: u64) -> std::result::Result<(), photocraft_io::IoError> {
        self.remaining =
            self.remaining.checked_sub(units).ok_or_else(|| photocraft_io::IoError::Unsupported("channel correspondence exceeds prepaid proof work".into()))?;
        Ok(())
    }
    fn take_exact(&mut self, units: u64) -> Result<Self> {
        self.remaining = self.remaining.checked_sub(units).ok_or_else(|| bad("actual selected verification exceeds prepaid bound"))?;
        // The unused parent receipt stays debited. No global work is refunded.
        Ok(Self { remaining: units })
    }
    fn finish(&self) -> Result<()> {
        if self.remaining != 0 {
            return Err(bad("channel correspondence did not consume its prepaid proof receipt"));
        }
        Ok(())
    }
}
fn bad(message: &str) -> EngineError {
    EngineError::BadParams { cmd: "xcf.channel.gaussian.prepare".into(), msg: message.into() }
}
fn add(a: u64, b: u64) -> Result<u64> {
    a.checked_add(b).ok_or_else(|| bad("channel accounting overflow"))
}
fn mul(a: u64, b: u64) -> Result<u64> {
    a.checked_mul(b).ok_or_else(|| bad("channel accounting overflow"))
}
fn poll(control: &Interrupt<'_>) -> Result<()> {
    control.check().map_err(|_| EngineError::Cancelled)
}
fn composition(error: CompositionError) -> EngineError {
    if matches!(error, CompositionError::Raster(photocraft_raster::RasterInputError::Cancelled)) {
        EngineError::Cancelled
    } else {
        EngineError::Other(error.to_string())
    }
}
fn idle(session: &Session) -> Result<()> {
    if session.documents().len() > 4096 {
        return Err(bad("document count limit"));
    }
    let current = session.active().ok_or(EngineError::NoDocument)?;
    if session.has_jobs()
        || session.command_has_pending_job()
        || session.command_is_background()
        || session.coalesce_request.is_some()
        || session.color_restrict.is_some()
        || current.coalesce.is_some()
        || current.floating.is_some()
        || current.revision == u64::MAX
        || current.doc.xcf_state.as_ref().is_some_and(|state| state.floating.is_some())
    {
        return Err(bad("finish pending work before channel preparation"));
    }
    Ok(())
}
fn copy_view(view: &ChannelView, maximum: u64, control: &Interrupt<'_>) -> Result<ChannelView> {
    let mut colors = Vec::new();
    let mut alphas = Vec::new();
    colors.try_reserve_exact(view.color_hidden.len()).map_err(|_| bad("view allocation"))?;
    alphas.try_reserve_exact(view.alpha_visible.len()).map_err(|_| bad("view allocation"))?;
    let actual = add(std::mem::size_of::<PreparedChannelGaussian<()>>() as u64, add(colors.capacity() as u64, alphas.capacity() as u64)?)?;
    if actual > maximum {
        return Err(bad("actual view capacity exceeds remaining envelope"));
    }
    for value in &view.color_hidden {
        poll(control)?;
        colors.push(*value);
    }
    for value in &view.alpha_visible {
        poll(control)?;
        alphas.push(*value);
    }
    Ok(ChannelView {
        target: view.target,
        color_hidden: colors,
        alpha_visible: alphas,
        quick_mask_hidden: view.quick_mask_hidden,
        layer_mask: view.layer_mask,
        editing_mask: view.editing_mask,
    })
}
fn view_bytes(view: &ChannelView, capacity: bool) -> Result<u64> {
    if view.color_hidden.len() > 16 || view.alpha_visible.len() > 10_000 {
        return Err(bad("view count limit"));
    }
    add(
        std::mem::size_of::<PreparedChannelGaussian<()>>() as u64,
        add(
            if capacity { view.color_hidden.capacity() } else { view.color_hidden.len() } as u64,
            if capacity { view.alpha_visible.capacity() } else { view.alpha_visible.len() } as u64,
        )?,
    )
}
fn inspectors(limits: Limits, held: u64, work: &Work, view: u64) -> Result<photocraft_format::PreparationLimits> {
    let available = limits.resident_bytes.checked_sub(held).ok_or_else(|| bad("resident envelope exhausted"))?.min(work.remaining());
    let available = usize::try_from(available).map_err(|_| bad("inspector range"))?;
    let index = usize::try_from(limits.index_bytes.checked_sub(view).ok_or_else(|| bad("index envelope exhausted"))?).map_err(|_| bad("index range"))?;
    let standard = photocraft_io::NativeSaveLimits::default().preparation;
    Ok(photocraft_format::PreparationLimits {
        resident_bytes: available,
        index_bytes: index.min(available).min(standard.index_bytes),
        manifest_bytes: available.min(standard.manifest_bytes),
        object_bytes: available.min(standard.object_bytes),
    })
}
fn correspondence_admission(requirements: photocraft_io::CorrespondenceRequirements, limits: Limits, view: u64, work: &Work) -> Result<()> {
    if requirements.resident_bytes > limits.resident_bytes
        || add(add(view, DERIVED_INDEX_RESERVATION)?, requirements.index_bytes)? > limits.index_bytes
        || requirements.work_units > work.remaining()
    {
        return Err(bad("complete correspondence owner exceeds remaining envelope"));
    }
    Ok(())
}
fn selected_verification_upper(source_work: u64, resident_limit: u64) -> Result<u64> {
    // Exact select_current formula is source.work +8*census.retained_bytes.
    // The genuine census must fit resident_limit before descriptor construction.
    add(source_work, mul(resident_limit, 8)?)
}
fn node<'a>(snapshot: &'a DocumentSnapshot, channel: ChannelId, control: &Interrupt<'_>) -> Result<&'a FilterNode> {
    xcf_channel_consumer::inspect_candidate(snapshot, channel, ChannelConsumer::StoredSelectionRead, control)?
        .map(|candidate| candidate.filter)
        .ok_or_else(|| bad("stored channel candidate unavailable"))
}
fn working(evidence: &WorkingDomainEvidence<'_>, binding: &SourceBinding<'_>, config: gaussian::Config) -> Result<()> {
    let format = match evidence.domain {
        gaussian::NativeDomain::SrgbNonlinearU8 => "Y' u8",
        gaussian::NativeDomain::SrgbLinearF64 => "Y double",
    };
    if evidence.native_format != format
        || evidence.native_space != "sRGB"
        || evidence.domain != config.domain
        || evidence.source_sha256.len() != 64
        || !evidence.source_sha256.bytes().all(|b| b.is_ascii_hexdigit())
        || !evidence.source_sha256.eq_ignore_ascii_case(binding.source_sha256())
    {
        return Err(bad("independent native working-domain evidence does not match source request"));
    }
    Ok(())
}
struct LocalBudget<'a> {
    held: u64,
    limit: u64,
    work: &'a Work,
}
impl PreparationBudget for LocalBudget<'_> {
    type Lease = ();
    fn reserve_prepared_bytes(&mut self, bytes: u64) -> ComposeResult<()> {
        self.held = self.held.checked_add(bytes).filter(|n| *n <= self.limit).ok_or(CompositionError::Invalid("channel remaining resident budget"))?;
        Ok(())
    }
    fn consume_preparation_work(&mut self, units: u64) -> ComposeResult<()> {
        self.work.charge(units).map_err(|_| CompositionError::Invalid("channel remaining work budget"))
    }
}
/// Owns source and derived stages separately. There is intentionally no commit,
/// mutable Surface, LoadProof, or channel-write authorization method.
pub struct PreparedChannelGaussian<L> {
    snapshot: DocumentSnapshot,
    revision: u64,
    active: Option<LayerId>,
    view: ChannelView,
    channel: ChannelId,
    source_bytes: Vec<u8>,
    correspondence: SourceCorrespondence,
    output: gaussian::StagedOutput<()>,
    requirements: Requirements,
    validation_work: u64,
    work: Work,
    _lease: L,
}
impl<L> PreparedChannelGaussian<L> {
    pub fn original_snapshot(&self) -> &DocumentSnapshot {
        &self.snapshot
    }
    pub fn channel(&self) -> ChannelId {
        self.channel
    }
    pub fn source_correspondence(&self) -> SourceCorrespondence {
        self.correspondence
    }
    pub fn derived_surface(&self) -> &Surface {
        self.output.surface()
    }
    pub fn config(&self) -> gaussian::Config {
        self.output.config()
    }
    pub fn requirements(&self) -> Requirements {
        self.requirements
    }
    pub fn remaining_work_units(&self) -> u64 {
        self.work.remaining()
    }
    /// Same retained ledger, including repeat hashes/namespace validation. This
    /// remains a stale/current proof only, never filtered-appearance authority.
    pub fn validate(&self, session: &Session, control: &Interrupt<'_>) -> Result<()> {
        self.work.charge(self.validation_work)?;
        let work = &self.work;
        let cancelled = || control.cancelled() || work.charge(1).is_err();
        let progress = |fraction| control.progress(fraction);
        let metered = Interrupt::new(&cancelled, &progress);
        let result = (|| {
            poll(&metered)?;
            idle(session)?;
            let current = session.active().ok_or(EngineError::NoDocument)?;
            if current.doc.id != self.snapshot.id
                || current.revision != self.revision
                || !current.doc.shares_state(&self.snapshot)
                || current.active_layer != self.active
                || current.channel_view != self.view
            {
                return Err(bad("channel preparation target changed"));
            }
            if self.correspondence == SourceCorrespondence::SelectedDecodedOriginalNativePlanes {
                // Genuine descriptor/proof checked the complete selected source
                // and captured refs once. Exact immutable snapshot identity keeps
                // those checks valid; do not traverse/qualify unrelated scene.
                return poll(&metered);
            }
            let original = node(&self.snapshot, self.channel, &metered)?;
            let binding = xcf_channel_consumer::bind_source(&self.source_bytes, self.channel, original, &metered)?;
            xcf_channel_consumer::read_stored(&current.doc, &binding, &metered)?;
            poll(&metered)
        })();
        if self.work.exceeded.load(Ordering::Relaxed) {
            return Err(bad("channel preparation work limit"));
        }
        result
    }
}

pub fn prepare<B: PreparationBudget>(
    session: &Session,
    channel: ChannelId,
    evidence: SourceEvidence<'_>,
    config: gaussian::Config,
    limits: Limits,
    budget: &mut B,
    control: &Interrupt<'_>,
) -> Result<PreparedChannelGaussian<B::Lease>> {
    prepare_input(session, channel, PreparationInput::Metadata(evidence), config, limits, budget, control)
}
/// The opaque IO owner holds independently decoded original backing. Its whole
/// resident/index envelope is charged in addition to current Document storage;
/// verification uses this operation's admitted meter before copies/Gaussian.
/// The working-domain observation is still a separate mandatory caller input.
/// On return the retained immutable current snapshot preserves the exact native
/// verification result even after this borrowed IO owner/proof is released.
#[allow(clippy::too_many_arguments)]
pub fn prepare_from_correspondence<B: PreparationBudget>(
    session: &Session,
    channel: ChannelId,
    owner: &photocraft_io::AssembledStoredChannel<'_, '_, '_>,
    working: WorkingDomainEvidence<'_>,
    config: gaussian::Config,
    limits: Limits,
    budget: &mut B,
    control: &Interrupt<'_>,
) -> Result<PreparedChannelGaussian<B::Lease>> {
    if owner.channel_id() != channel {
        return Err(bad("correspondence owner belongs to a different channel"));
    }
    prepare_input(session, channel, PreparationInput::Correspondence { owner, working }, config, limits, budget, control)
}
/// Selected channel/mask correspondence inside a retained full current scene.
/// Native census receipts are generated from the actual captured Document under
/// this lease; no externally asserted census totals or whole-scene qualification.
#[allow(clippy::too_many_arguments)]
pub fn prepare_from_selected_correspondence<B: PreparationBudget>(
    session: &Session,
    channel: ChannelId,
    owner: &photocraft_io::AssembledStoredChannel<'_, '_, '_>,
    working: WorkingDomainEvidence<'_>,
    config: gaussian::Config,
    limits: Limits,
    budget: &mut B,
    control: &Interrupt<'_>,
) -> Result<PreparedChannelGaussian<B::Lease>> {
    if owner.channel_id() != channel {
        return Err(bad("selected correspondence owner belongs to a different channel"));
    }
    prepare_input(session, channel, PreparationInput::Selected { owner, working }, config, limits, budget, control)
}
#[allow(clippy::too_many_arguments)]
fn prepare_input<B: PreparationBudget>(
    session: &Session,
    channel: ChannelId,
    input: PreparationInput<'_, '_, '_, '_>,
    config: gaussian::Config,
    limits: Limits,
    budget: &mut B,
    control: &Interrupt<'_>,
) -> Result<PreparedChannelGaussian<B::Lease>> {
    poll(control)?;
    idle(session)?;
    let standard = Limits::default();
    if limits.resident_bytes > standard.resident_bytes
        || limits.index_bytes > standard.index_bytes
        || limits.work_units > standard.work_units
        || input.original_bytes().is_empty()
        || input.original_bytes().len() > 16_384
        || channel.0 == 0
    {
        return Err(bad("channel preparation input or lower-only limits"));
    }
    let current = session.active().ok_or(EngineError::NoDocument)?;
    let requested_view = view_bytes(&current.channel_view, false)?;
    if requested_view > limits.index_bytes || requested_view > limits.resident_bytes {
        return Err(bad("view admission"));
    }
    // One external lease covers census scratch, complete retained original and
    // private stages. The work envelope is debited once, including failures.
    budget.consume_preparation_work(limits.work_units).map_err(composition)?;
    let lease = budget.reserve_prepared_bytes(limits.resident_bytes).map_err(composition)?;
    let work = Work { used: AtomicU64::new(0), exceeded: AtomicBool::new(false), limit: limits.work_units };
    let cancelled = || control.cancelled() || work.charge(1).is_err();
    let progress = |fraction| control.progress(fraction);
    let metered = Interrupt::new(&cancelled, &progress);
    let staged = (|| {
        let input_bytes = input.original_bytes().len() as u64;
        work.charge(add(requested_view, input_bytes)?)?;
        let correspondence_requirements = match &input {
            PreparationInput::Metadata(_) => photocraft_io::CorrespondenceRequirements { resident_bytes: 0, index_bytes: 0, work_units: 0 },
            PreparationInput::Correspondence { owner, .. } | PreparationInput::Selected { owner, .. } => {
                owner.correspondence_requirements().map_err(|e| EngineError::Other(e.to_string()))?
            }
        };
        correspondence_admission(correspondence_requirements, limits, requested_view, &work)?;
        let selected_lane = matches!(&input, PreparationInput::Selected { .. });
        // This is the actual IO constructor formula: source.work +8*current
        // census retention. Current retention must fit the lower resident
        // envelope; reserve its conservative bound before any census traversal.
        let prepaid_units = if selected_lane {
            selected_verification_upper(correspondence_requirements.work_units, limits.resident_bytes)?
        } else {
            correspondence_requirements.work_units
        };
        // Do not let hierarchy/model/payload census spend work promised to the
        // opaque proof. IO's callback consumes this reservation without another
        // global charge; failure/unused receipt never resets or refunds Work.
        let mut proof_work = PrepaidProofWork::reserve(&work, prepaid_units)?;
        // Resident variant and hierarchy admission occur only after the full
        // envelope is held, using the same polled work/cancellation ledger.
        let resident = current.doc.resident_arc().ok_or(photocraft_raster::backing::BackingError::Unsupported)?;
        let backed = photocraft_doc::resident_structure::has_backed_rasters_with(resident, &metered).map_err(|error| {
            if error == photocraft_raster::RasterInputError::Cancelled {
                photocraft_raster::backing::BackingError::Cancelled
            } else {
                photocraft_raster::backing::BackingError::Bounds
            }
        })?;
        if backed {
            return Err(photocraft_raster::backing::BackingError::Unsupported.into());
        }
        let raster = current.doc.resident_raster_footprint_with(&metered)?;
        let mut held = add(
            correspondence_requirements.resident_bytes,
            add(add(raster.retained_bytes, mul(raster.clone_metadata_bytes, 4)?)?, add(requested_view, input_bytes)?)?,
        )?;
        let prospective_index = add(add(requested_view, DERIVED_INDEX_RESERVATION)?, correspondence_requirements.index_bytes)?;
        let mut model_limits = inspectors(limits, held, &work, prospective_index)?;
        model_limits.resident_bytes /= 4;
        model_limits.index_bytes = model_limits.index_bytes.min(model_limits.resident_bytes);
        model_limits.manifest_bytes = model_limits.manifest_bytes.min(model_limits.resident_bytes);
        model_limits.object_bytes = model_limits.object_bytes.min(model_limits.resident_bytes);
        let mut scratch = model_limits.index_bytes as u64;
        let model_census = photocraft_io::retained_native_model_census(&current.doc, model_limits, &metered)
            .map_err(|e| if metered.cancelled() { EngineError::Cancelled } else { EngineError::Other(e.to_string()) })?;
        let model = model_census.retained_bytes() as u64;
        work.charge(model)?;
        held = add(held, mul(model, 4)?)?;
        let payload_limits = inspectors(limits, held, &work, prospective_index)?;
        scratch = scratch.max(payload_limits.index_bytes as u64);
        let payload_census = photocraft_io::retained_native_payload_census(&current.doc, payload_limits, &metered)
            .map_err(|e| if metered.cancelled() { EngineError::Cancelled } else { EngineError::Other(e.to_string()) })?;
        let payload = payload_census.retained_bytes() as u64;
        work.charge(payload)?;
        held = add(held, payload)?;
        if add(held, scratch)? > limits.resident_bytes {
            return Err(bad("source and census scratch admission"));
        }
        let state = current.doc.xcf_state.as_ref().ok_or_else(|| bad("missing original channel state"))?;
        let repeats = [state.source_items.len(), state.resources.len(), state.opaque.len(), state.editable_indexed.len(), state.filter_masks.len()]
            .into_iter()
            .try_fold(3_u64, |n, count| add(n, count as u64))?;
        let validation_work = if selected_lane { add(requested_view, input_bytes)? } else { add(mul(add(model, payload)?, repeats)?, input_bytes)? };
        work.charge(validation_work)?;
        let selected;
        let mut selected_resident = held;
        let mut selected_index = 0;
        let mut selected_namespace_work = 0;
        let mut verification_work = correspondence_requirements.work_units;
        if let PreparationInput::Selected { owner, .. } = &input {
            let census = photocraft_io::NativeCurrentCensus::join(model_census, payload_census).map_err(|e| EngineError::Other(e.to_string()))?;
            // IO's complete envelope includes actual census model/payload/maps,
            // original owner and descriptor/namespace scratch. Add our retained
            // raster/COW, extra clone model and future view/source-copy envelope.
            let extra = add(add(raster.retained_bytes, mul(raster.clone_metadata_bytes, 4)?)?, add(mul(model, 3)?, add(requested_view, input_bytes)?)?)?;
            let selected_limits = photocraft_io::SelectedLimits {
                resident_bytes: limits.resident_bytes.checked_sub(extra).ok_or_else(|| bad("selected descriptor resident envelope"))?,
                index_bytes: limits
                    .index_bytes
                    .checked_sub(add(requested_view, DERIVED_INDEX_RESERVATION)?)
                    .ok_or_else(|| bad("selected descriptor index envelope"))?,
                work_units: add(work.remaining(), proof_work.remaining)?,
            };
            selected = Some(
                photocraft_io::select_current(
                    census,
                    owner,
                    selected_limits,
                    &metered,
                    &mut |resident, index| {
                        let total = add(resident, extra).map_err(|e| photocraft_io::IoError::Unsupported(e.to_string()))?;
                        let index_total =
                            add(index, add(requested_view, DERIVED_INDEX_RESERVATION).map_err(|e| photocraft_io::IoError::Unsupported(e.to_string()))?)
                                .map_err(|e| photocraft_io::IoError::Unsupported(e.to_string()))?;
                        if total > limits.resident_bytes || index_total > limits.index_bytes {
                            return Err(photocraft_io::IoError::Unsupported("selected descriptor exceeds shared envelope".into()));
                        }
                        selected_resident = total;
                        selected_index = index;
                        Ok(())
                    },
                    &mut |units| work.charge(units).map_err(|e| photocraft_io::IoError::Unsupported(e.to_string())),
                )
                .map_err(|e| if metered.cancelled() { EngineError::Cancelled } else { EngineError::Other(e.to_string()) })?,
            );
            let descriptor = selected.as_ref().ok_or_else(|| bad("missing selected descriptor"))?;
            let required = descriptor.requirements();
            selected_namespace_work = required.selection_work_units;
            verification_work = required.verification_work_units;
            if verification_work > prepaid_units {
                return Err(bad("genuine selected verification exceeds prepaid formula"));
            }
        } else {
            selected = None;
        }
        // Only this opaque IO verification can construct the stronger input.
        // The original metadata-only compatibility route is left unchanged.
        let proof = match &input {
            PreparationInput::Metadata(_) => None,
            PreparationInput::Correspondence { owner, .. } => Some(
                owner
                    .verify_document_with_charge(&current.doc, &metered, &mut |units| proof_work.consume(units))
                    .map_err(|e| if metered.cancelled() { EngineError::Cancelled } else { EngineError::Other(e.to_string()) })?,
            ),
            PreparationInput::Selected { owner, .. } => {
                let descriptor = selected.as_ref().ok_or_else(|| bad("missing selected descriptor"))?;
                let mut exact_work = proof_work.take_exact(verification_work)?;
                let proof = owner
                    .verify_selected_with_charge(descriptor, &metered, &mut |units| exact_work.consume(units))
                    .map_err(|e| if metered.cancelled() { EngineError::Cancelled } else { EngineError::Other(e.to_string()) })?;
                exact_work.finish()?;
                Some(proof)
            }
        };
        if !selected_lane {
            proof_work.finish()?;
        }
        let (evidence, correspondence) = match input {
            PreparationInput::Metadata(evidence) => (evidence, SourceCorrespondence::MetadataOnly),
            PreparationInput::Correspondence { owner, working } | PreparationInput::Selected { owner, working } => {
                let verified = proof.as_ref().ok_or_else(|| bad("missing opaque correspondence result"))?;
                if !std::ptr::eq(verified.document(), &*current.doc)
                    || verified.channel_id() != channel
                    || verified.original_node().mask != Some(ItemRef::Mask(verified.mask_id()))
                    || verified.source_sha256() != owner.source_sha256()
                    || verified.original_bytes() != owner.original_bytes()
                {
                    return Err(bad("opaque correspondence result differs from captured owner"));
                }
                (
                    SourceEvidence { original_bytes: verified.original_bytes(), original_node: verified.original_node(), working },
                    if selected_lane { SourceCorrespondence::SelectedDecodedOriginalNativePlanes } else { SourceCorrespondence::DecodedOriginalNativePlanes },
                )
            }
        };
        let binding = xcf_channel_consumer::bind_source(evidence.original_bytes, channel, evidence.original_node, &metered)?;
        working(&evidence.working, &binding, config)?;
        let read = if let Some(selected) = selected.as_ref() {
            xcf_channel_consumer::read_stored_from_selected_correspondence(
                &current.doc,
                &binding,
                selected,
                proof.as_ref().ok_or_else(|| bad("missing selected proof"))?,
                &metered,
            )?
        } else {
            xcf_channel_consumer::read_stored(&current.doc, &binding, &metered)?
        };
        let actual_node = if let Some(selected) = selected.as_ref() { selected.original_node() } else { node(&current.doc, channel, &metered)? };
        // Bind the explicit numerical sigma request to exact scalar source words;
        // raw type5 enum/outer tuple words are not converted into Auto or Clamp.
        for (name, value) in [("std-dev-x", config.gaussian.std_dev_x), ("std-dev-y", config.gaussian.std_dev_y)] {
            let argument = actual_node.arguments.iter().find(|a| a.name == name).ok_or_else(|| bad("missing original scalar"))?;
            if !matches!(argument.value, photocraft_doc::xcf_filters::FilterValue::Number(photocraft_doc::xcf_filters::ExactNumber::Float32Bits(bits)) if f64::from(f32::from_bits(bits)) == value)
            {
                return Err(bad("explicit Gaussian sigma differs from bound original scalar"));
            }
        }
        let ItemRef::Mask(mask_id) = actual_node.mask.ok_or_else(|| bad("missing original mask"))? else {
            return Err(bad("wrong original mask kind"));
        };
        let mut mask = selected.as_ref().map(|selected| selected.filter_mask());
        if !selected_lane {
            for value in &state.filter_masks {
                poll(&metered)?;
                if value.id == mask_id && mask.replace(value).is_some() {
                    return Err(bad("duplicate original mask mapping"));
                }
            }
        }
        let mask = mask.ok_or_else(|| bad("missing original mask mapping"))?;
        if mask.bounds != binding.mask_bounds() {
            return Err(bad("original mask geometry changed"));
        }
        if selected_lane {
            // Temporary inspector sets are gone; no full validator follows in
            // this lane. Retain the genuine descriptor's complete namespace
            // allowance instead, while the outer envelope lease remains held.
            held = selected_resident;
            scratch = selected_index;
        }
        let additional_scratch = if selected_lane { 0 } else { scratch };
        let max_view_resident = limits
            .resident_bytes
            .checked_sub(add(held.checked_sub(requested_view).ok_or_else(|| bad("view accounting underflow"))?, additional_scratch)?)
            .ok_or_else(|| bad("view remaining resident envelope"))?;
        let retained_owner_index = if selected_lane { 0 } else { correspondence_requirements.index_bytes };
        let max_view_index = limits
            .index_bytes
            .checked_sub(add(add(scratch, DERIVED_INDEX_RESERVATION)?, retained_owner_index)?)
            .ok_or_else(|| bad("view remaining index envelope"))?;
        let view = copy_view(&current.channel_view, max_view_resident.min(max_view_index), &metered)?;
        let actual_view = view_bytes(&view, true)?;
        let mut source_bytes = Vec::new();
        source_bytes.try_reserve_exact(evidence.original_bytes.len()).map_err(|_| bad("original binding allocation"))?;
        held = add(
            held.checked_sub(add(requested_view, evidence.original_bytes.len() as u64)?).ok_or_else(|| bad("source accounting underflow"))?,
            add(actual_view, source_bytes.capacity() as u64)?,
        )?;
        // Keep the conservative census/validation scratch allowance throughout
        // derived preparation and every later source/current validation.
        if !selected_lane {
            held = add(held, scratch)?;
        }
        let source_index = add(add(actual_view, scratch)?, retained_owner_index)?;
        if held > limits.resident_bytes || add(source_index, DERIVED_INDEX_RESERVATION)? > limits.index_bytes {
            return Err(bad("actual source/view capacity admission"));
        }
        source_bytes.extend_from_slice(evidence.original_bytes);
        let remaining = Limits {
            resident_bytes: limits.resident_bytes.checked_sub(held).ok_or_else(|| bad("no derived resident budget"))?,
            index_bytes: limits.index_bytes.checked_sub(source_index).ok_or_else(|| bad("no derived index budget"))?,
            work_units: work.remaining(),
        };
        let mut local = LocalBudget { held, limit: limits.resident_bytes, work: &work };
        let output = gaussian::prepare(
            gaussian::Original { surface: read.surface, bounds: read.bounds, node: actual_node, mask: Some(mask), opaque: &state.opaque },
            config,
            remaining,
            &mut local,
            &metered,
        )
        .map_err(composition)?
        .into_staged();
        if output.requirements().index_bytes > DERIVED_INDEX_RESERVATION {
            return Err(bad("derived index exceeds prospective reservation"));
        }
        let requirements = Requirements {
            admitted_resident_bytes: limits.resident_bytes,
            admitted_work_units: limits.work_units,
            source_raster_bytes: raster.retained_bytes,
            source_model_bytes: model,
            source_payload_bytes: payload,
            source_and_view_bytes: held,
            correspondence_owner_bytes: correspondence_requirements.resident_bytes,
            correspondence_owner_index_bytes: correspondence_requirements.index_bytes,
            correspondence_verification_work: verification_work,
            correspondence_prepaid_work_units: prepaid_units,
            selected_namespace_work_units: selected_namespace_work,
            index_envelope_bytes: limits.index_bytes,
            preparation_work_units: 0,
            derived: output.requirements(),
        };
        Ok((current.doc.clone(), current.revision, current.active_layer, view, source_bytes, correspondence, output, requirements, validation_work))
    })();
    if work.exceeded.load(Ordering::Relaxed) {
        return Err(bad("channel preparation work limit"));
    }
    let (snapshot, revision, active, view, source_bytes, correspondence, output, requirements, validation_work) = staged?;
    let mut prepared = PreparedChannelGaussian {
        snapshot,
        revision,
        active,
        view,
        channel,
        source_bytes,
        correspondence,
        output,
        requirements,
        validation_work,
        work,
        _lease: lease,
    };
    prepared.validate(session, control)?;
    prepared.requirements.preparation_work_units = prepared.work.used.load(Ordering::Relaxed);
    Ok(prepared)
}

