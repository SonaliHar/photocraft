struct GrayRetention {
    _source: Arc<SourceGuard>,
    _index: QuotaLease,
}
fn gray(sample: SampleType) -> (Document, BackingQuota, Arc<GrayRetention>) {
    let q = quota();
    let index = q.reserve(QuotaKind::Index, 2 << 20).unwrap();
    let (mut doc, source) = fixture(&q, sample, SampleEncoding::NonlinearProfile, if sample == SampleType::F32 { 650 } else { 750 });
    let format = PixelFormat::new(ColorMode::Grayscale, sample, true);
    let bounds = Rect::new(-13, 13, 244, 142);
    let mut default = vec![0; format.bytes_per_pixel()];
    if sample == SampleType::F64 {
        default[..8].copy_from_slice(&(-0f64).to_ne_bytes());
    }
    let descriptor = NativePlaneDescriptor::new(format, bounds, &default).unwrap();
    let raster = BackedRaster::new(Arc::new(Store { descriptor, _guard: source.clone() }), q.clone(), 1, &ctl()).unwrap();
    // Replace the RGB fixture's native store with a genuine Gray+alpha store,
    // not just its model label. Both stores/metadata allocations are prepaid;
    // the temporary RGB backing drops here, without a retained model chain.
    doc.mode = ColorMode::Grayscale;
    doc.layers[0].content = LayerContent::BackedRaster(BackedLayer::new(raster, descriptor, &ctl()).unwrap());
    let mut icc = Vec::with_capacity(4096);
    icc.extend_from_slice(PRODUCER_GRAY_ICC);
    doc.icc_profile = Some(Arc::new(icc));
    doc.working_profile_interpretation = crate::WorkingProfileInterpretation::implicit_sgray(doc.icc_profile.as_ref().unwrap());
    (doc, q, Arc::new(GrayRetention { _source: source, _index: index }))
}
fn owner(sample: SampleType) -> AccountedDocument {
    let (doc, q, guard) = gray(sample);
    AccountedDocument::new_readonly_point_storage(doc, guard, q, &ctl()).unwrap()
}
fn leaf(owner: &AccountedDocument) -> &BackedLayer {
    let LayerContent::BackedRaster(v) = &owner.document().layers[0].content else { panic!("fixture") };
    v
}
fn same_custody(a: &AccountedDocument, b: &AccountedDocument) {
    assert!(b.is_readonly_point_storage());
    assert!(!b.is_readonly_assigned_point_storage());
    assert_eq!(b.document().mode, ColorMode::Grayscale);
    assert!(a.quota().shares_ledger(b.quota()));
    assert_eq!(a.document().source_color_context, b.document().source_color_context);
    assert!(b.document().source_color_context.as_ref().unwrap().original_icc.is_none());
    assert!(Arc::ptr_eq(a.document().icc_profile.as_ref().unwrap(), b.document().icc_profile.as_ref().unwrap()));
    assert_eq!(a.document().working_profile_interpretation, b.document().working_profile_interpretation);
    assert_eq!(leaf(a).default_bytes(), leaf(b).default_bytes());
    let sa = a.document().xcf_state.as_ref().unwrap();
    let sb = b.document().xcf_state.as_ref().unwrap();
    assert_eq!(sa.filter_stacks, sb.filter_stacks);
    assert_eq!(sa.filter_masks, sb.filter_masks);
    assert_eq!(sa.provenance, sb.provenance);
    assert_eq!(sa.opaque, sb.opaque);
    for (ma, mb) in sa.filter_masks.iter().zip(&sb.filter_masks) {
        for ((ca, ta), (cb, tb)) in ma.surface.tiles().zip(mb.surface.tiles()) {
            assert_eq!(ca, cb);
            assert!(Arc::ptr_eq(ta, tb));
        }
    }
}
#[test]
#[ignore = "UNRUN Gray2 native and Gray1 mask widths, marker role and assigned Gray refusal"]
fn gray_storage_has_actual_native_arity_and_separate_profile_identity() {
    assert_eq!(&PRODUCER_GRAY_ICC[16..20], b"GRAY");
    for sample in [SampleType::F32, SampleType::F64] {
        let old = owner(sample);
        old.validate_readonly_point_storage(&ctl()).unwrap();
        let doc = old.document();
        let icc = doc.icc_profile.as_ref().unwrap();
        assert_eq!(icc.as_slice(), PRODUCER_GRAY_ICC);
        assert!(icc.capacity() >= 4096);
        assert_eq!(leaf(&old).format().channels(), 2);
        assert_eq!(leaf(&old).format().bytes_per_pixel(), 2 * sample.bytes());
        let mask = &doc.xcf_state.as_ref().unwrap().filter_masks[0];
        assert_eq!(mask.surface.format().channels(), 1);
        assert_eq!(mask.surface.format().bytes_per_pixel(), sample.bytes());
        assert_eq!(leaf(&old).default_bytes().len(), 2 * sample.bytes());
        assert_eq!(mask.surface.default_bytes().len(), sample.bytes());
        doc.working_profile_interpretation.validate_with(Some(icc), ColorMode::Grayscale).unwrap();
        assert!(crate::WorkingProfileInterpretation::implicit_srgb(icc).validate_with(Some(icc), ColorMode::Grayscale).is_err());
        assert!(doc.working_profile_interpretation.validate_with(Some(icc), ColorMode::Rgb).is_err());
        // Marker model/hash identity is separate from CMS encoded-definition
        // equality; no RGB/Gray profile semantics are added to L1 custody.
        let (mut assigned, q, guard) = gray(sample);
        assigned.source_color_context.as_mut().unwrap().original_icc = assigned.icc_profile.clone();
        assigned.working_profile_interpretation = crate::WorkingProfileInterpretation::Icc;
        assert!(AccountedDocument::readonly_point_storage_requirements(&assigned, &q, &ctl()).is_err());
        assert!(AccountedDocument::new_readonly_assigned_point_storage(assigned, guard, q.clone(), &ctl()).is_err());
        assert_eq!(q.usage().unwrap(), Default::default());
    }
}
#[test]
#[ignore = "UNRUN Gray COW sample/alpha raw bits through compound metadata and Move with fixed filter mask"]
fn gray_native_words_move_without_rgb_expansion_or_mask_motion() {
    for sample in [SampleType::F32, SampleType::F64] {
        let mut old = owner(sample);
        let id = old.document().layers[0].id;
        let words: Vec<u8> = [-0.0f64, 0.375]
            .into_iter()
            .flat_map(|v| if sample == SampleType::F32 { (v as f32).to_ne_bytes().to_vec() } else { v.to_ne_bytes().to_vec() })
            .collect();
        let before = old.quota().usage().unwrap();
        let native = leaf(&old).try_edited_native(Rect::new(0, 14, 1, 15), &words, &ctl()).unwrap();
        // Real COW fees use YA8/16, never RGBA16/32. Incoming fixture mask/data
        // receipts do not substitute for private backing allocation overlap.
        assert!(old.quota().usage().unwrap().resident >= before.resident + (256 * 256 * 2 * sample.bytes()) as u64);
        Arc::get_mut(&mut old.owner).unwrap().document.layers[0].content = LayerContent::BackedRaster(native);
        let metadata =
            old.try_edit(AccountedEdit::LayerMetadata { layer: id, name: Some(" Gray 名 "), visible: Some(false), opacity: Some(-0.0) }, &ctl()).unwrap();
        let moved = metadata.try_with_readonly_point_layer_translation(id, -257, 259, &ctl()).unwrap();
        same_custody(&old, &moved);
        let mut actual = vec![0; 2 * sample.bytes()];
        leaf(&moved).checked_view().read_pixel_native_into(-257, 273, &mut actual, &ctl()).unwrap();
        assert_eq!(actual, words);
        let mut original = vec![0; 2 * sample.bytes()];
        leaf(&old).checked_view().read_pixel_native_into(0, 14, &mut original, &ctl()).unwrap();
        assert_eq!(original, words);
        let item = moved.document().xcf_state.as_ref().unwrap().items.iter().find(|v| v.item == ItemRef::Layer(id)).unwrap();
        assert_eq!(item.name, " Gray 名 ");
        assert!(!item.visible);
        assert_eq!(item.raster_bounds, Some(leaf(&moved).operative_bounds()));
        assert_eq!(moved.document().layers[0].opacity.to_bits(), (-0f32).to_bits());
        assert_eq!(moved.document().xcf_state.as_ref().unwrap().filter_masks[0].bounds, moved.document().bounds());
    }
}
#[test]
#[ignore = "UNRUN malformed native/canonical map and marker identity preflight without repair grants"]
fn malformed_gray_prestate_refuses_zero_noop_and_requested_repair() {
    for sample in [SampleType::F32, SampleType::F64] {
        let old = owner(sample);
        let bytes = old.document().icc_profile.as_ref().unwrap();
        assert!(crate::WorkingProfileInterpretation::ImplicitSGray { icc_blake3: "bad".into() }.validate_with(Some(bytes), ColorMode::Grayscale).is_err());
        for defect in 0..4 {
            let mut bad = owner(sample);
            let id = bad.document().layers[0].id;
            let doc = &mut Arc::get_mut(&mut bad.owner).unwrap().document;
            if defect == 3 {
                doc.mode = ColorMode::Rgb;
            } else {
                let item = doc.xcf_state.as_mut().unwrap().items.iter_mut().find(|v| v.item == ItemRef::Layer(id)).unwrap();
                match defect {
                    0 => item.name = "divergent".into(),
                    1 => item.visible = false,
                    _ => item.raster_bounds = None,
                }
            }
            let before = bad.quota().usage().unwrap();
            for request in [
                AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None },
                AccountedEdit::LayerMetadata { layer: id, name: Some("original layer"), visible: Some(true), opacity: Some(1.0) },
            ] {
                assert!(bad.try_edit(request, &ctl()).is_err());
            }
            assert!(bad.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).is_err());
            assert_eq!(bad.quota().usage().unwrap(), before);
        }
    }
}
#[test]
#[ignore = "UNRUN Gray real quota/work/cancel and flat codec lifetime under title and Move"]
fn gray_paid_failures_and_copy_chain_preserve_source_owners() {
    for sample in [SampleType::F32, SampleType::F64] {
        let old = owner(sample);
        let id = old.document().layers[0].id;
        let q = old.quota().clone();
        let before = q.usage().unwrap();
        let index = q.reserve(QuotaKind::Index, (16 << 20) - before.index).unwrap();
        assert!(old.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).unwrap().shares_model(&old));
        assert!(old.try_with_document_name("changed", &ctl()).is_err());
        drop(index);
        let deny = ReadControl { interrupt: &Interrupt::NONE, work: &|_| Err(BackingError::Work) };
        assert!(old.try_with_readonly_point_layer_translation(id, 1, 0, &deny).is_err());
        let allocated = || q.usage().unwrap().index > before.index;
        let stop = Interrupt::cancel_only(&allocated);
        assert!(old.try_with_document_name("changed", &ReadControl { interrupt: &stop, work: &|_| Ok(()) }).is_err());
        assert_eq!(q.usage().unwrap(), before);
        let first = old.try_with_readonly_point_layer_translation(id, 1, -1, &ctl()).unwrap();
        let weak = Arc::downgrade(&first.owner);
        let last = first.try_with_document_name("Gray continued", &ctl()).unwrap();
        same_custody(&old, &last);
        assert!(last.owner.retention.downcast_ref::<OriginalRetention>().unwrap().original.shares_model(&old));
        drop(first);
        assert!(weak.upgrade().is_none());
        assert!(last.try_edit(AccountedEdit::LayerVisibility { layer: id, visible: false }, &ctl()).is_err());
        assert!(last.try_replace_selection(None, &ctl()).is_err());
        drop(old);
        drop(last);
        assert_eq!(q.usage().unwrap(), Default::default());
    }
}
