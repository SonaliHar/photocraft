fn roles() -> [(SampleType, SampleEncoding, u32); 4] {
    [
        (SampleType::F32, SampleEncoding::Linear, 600),
        (SampleType::F64, SampleEncoding::Linear, 700),
        (SampleType::F32, SampleEncoding::Perceptual, 675),
        (SampleType::F64, SampleEncoding::Perceptual, 775),
    ]
}
fn transfer(sample: SampleType, encoding: SampleEncoding, precision: u32) -> (Document, BackingQuota, Arc<GrayRetention>) {
    let (mut doc, q, guard) = gray(sample);
    // Existing Index prehold precedes these replacement profile/marker allocations;
    // existing Resident prehold owns actual Gray mask/model/source data. COW below
    // acquires separate backing leases. No fake RGB descriptor relabeling.
    doc.sample_encoding = Some(encoding);
    doc.source_color_context.as_mut().unwrap().source_precision = precision;
    let mut bytes = Vec::with_capacity(4096);
    bytes.extend_from_slice(if encoding == SampleEncoding::Linear { LINEAR_ICC } else { PERCEPTUAL_ICC });
    doc.icc_profile = Some(Arc::new(bytes));
    doc.working_profile_interpretation = crate::WorkingProfileInterpretation::implicit_sgray(doc.icc_profile.as_ref().unwrap());
    (doc, q, guard)
}
fn transfer_owner(sample: SampleType, encoding: SampleEncoding, precision: u32) -> AccountedDocument {
    let (doc, q, guard) = transfer(sample, encoding, precision);
    AccountedDocument::new_readonly_point_storage(doc, guard, q, &ctl()).unwrap()
}
#[test]
#[ignore = "UNRUN four Gray transfer roles retain distinct producer bytes/YA arity; cross-pairs and assigned Gray refuse"]
fn four_roles_are_data_custody_not_profile_aliases() {
    assert_ne!(LINEAR_ICC, PERCEPTUAL_ICC);
    assert_ne!(LINEAR_ICC, PRODUCER_GRAY_ICC);
    assert_ne!(PERCEPTUAL_ICC, PRODUCER_GRAY_ICC);
    for (sample, encoding, precision) in roles() {
        let old = transfer_owner(sample, encoding, precision);
        old.validate_readonly_point_storage(&ctl()).unwrap();
        let doc = old.document();
        let icc = doc.icc_profile.as_ref().unwrap();
        assert_eq!(icc.as_slice(), if encoding == SampleEncoding::Linear { LINEAR_ICC } else { PERCEPTUAL_ICC });
        assert_eq!(&icc[16..20], b"GRAY");
        assert!(icc.capacity() >= 4096);
        assert_eq!(doc.sample_encoding, Some(encoding));
        assert_eq!(doc.source_color_context.as_ref().unwrap().source_precision, precision);
        assert!(doc.source_color_context.as_ref().unwrap().original_icc.is_none());
        assert_eq!(leaf(&old).format().channels(), 2);
        assert_eq!(leaf(&old).format().bytes_per_pixel(), 2 * sample.bytes());
        let mask = &doc.xcf_state.as_ref().unwrap().filter_masks[0];
        assert_eq!(mask.surface.format().channels(), 1);
        assert_eq!(mask.surface.format().bytes_per_pixel(), sample.bytes());
        doc.working_profile_interpretation.validate_with(Some(icc), ColorMode::Grayscale).unwrap();
        // Precision refusal tests a real encoding/depth mismatch, not Half codes
        // which the preexisting structural table also intentionally supports.
        let (mut bad, q, guard) = transfer(sample, encoding, precision);
        bad.source_color_context.as_mut().unwrap().source_precision = if sample == SampleType::F32 { 700 } else { 600 };
        assert!(AccountedDocument::new_readonly_point_storage(bad, guard, q.clone(), &ctl()).is_err());
        assert_eq!(q.usage().unwrap(), Default::default());
        let (mut assigned, q, guard) = transfer(sample, encoding, precision);
        assigned.source_color_context.as_mut().unwrap().original_icc = assigned.icc_profile.clone();
        assigned.working_profile_interpretation = crate::WorkingProfileInterpretation::Icc;
        assert!(AccountedDocument::new_readonly_assigned_point_storage(assigned, guard, q.clone(), &ctl()).is_err());
        assert_eq!(q.usage().unwrap(), Default::default());
    }
}
#[test]
#[ignore = "UNRUN YA native low bits/defaults and fixed filter mask survive combined metadata/Move/title"]
fn transfer_copy_preserves_two_channel_native_words_and_raw_owners() {
    for (sample, encoding, precision) in roles() {
        let mut old = transfer_owner(sample, encoding, precision);
        let id = old.document().layers[0].id;
        // Adjacent representable values expose F64 narrowing; -0 is a native
        // default bit below, while alpha is a distinct second native channel.
        let words: Vec<u8> = if sample == SampleType::F64 {
            [f64::from_bits(0x3fd0_0000_0000_0001), f64::from_bits(0x3fe0_0000_0000_0001)].into_iter().flat_map(f64::to_ne_bytes).collect()
        } else {
            [f32::from_bits(0x3e80_0001), f32::from_bits(0x3f00_0001)].into_iter().flat_map(f32::to_ne_bytes).collect()
        };
        let native = leaf(&old).try_edited_native(Rect::new(0, 14, 1, 15), &words, &ctl()).unwrap();
        Arc::get_mut(&mut old.owner).unwrap().document.layers[0].content = LayerContent::BackedRaster(native);
        let metadata = old
            .try_edit(AccountedEdit::LayerMetadata { layer: id, name: Some(" Gray transfer 名 "), visible: Some(false), opacity: Some(-0.0) }, &ctl())
            .unwrap();
        let moved = metadata.try_with_readonly_point_layer_translation(id, -257, 259, &ctl()).unwrap();
        let last = moved.try_with_document_name("transfer continued", &ctl()).unwrap();
        same_custody(&old, &last);
        assert_eq!(last.document().sample_encoding, Some(encoding));
        let mut actual = vec![0; 2 * sample.bytes()];
        leaf(&last).checked_view().read_pixel_native_into(-257, 273, &mut actual, &ctl()).unwrap();
        assert_eq!(actual, words);
        leaf(&old).checked_view().read_pixel_native_into(0, 14, &mut actual, &ctl()).unwrap();
        assert_eq!(actual, words);
        if sample == SampleType::F64 {
            assert_eq!(&leaf(&last).default_bytes()[..8], &(-0f64).to_ne_bytes());
        }
        let item = last.document().xcf_state.as_ref().unwrap().items.iter().find(|v| v.item == ItemRef::Layer(id)).unwrap();
        assert_eq!(item.name, " Gray transfer 名 ");
        assert!(!item.visible);
        assert_eq!(item.raster_bounds, Some(leaf(&last).operative_bounds()));
        assert_eq!(last.document().layers[0].opacity.to_bits(), (-0f32).to_bits());
        let mask = &last.document().xcf_state.as_ref().unwrap().filter_masks[0];
        assert_eq!(mask.bounds, last.document().bounds());
        assert_eq!(mask.surface.default_bytes(), old.document().xcf_state.as_ref().unwrap().filter_masks[0].surface.default_bytes());
        assert!(last.owner.retention.downcast_ref::<OriginalRetention>().unwrap().original.shares_model(&old));
    }
}
#[test]
#[ignore = "UNRUN canonical malformed prestate refuses no-op/repair; marker checks remain separate from CMS"]
fn transfer_canonical_preflight_and_marker_identity_are_separate_contracts() {
    for (sample, encoding, precision) in roles() {
        let old = transfer_owner(sample, encoding, precision);
        let icc = old.document().icc_profile.as_ref().unwrap();
        assert!(crate::WorkingProfileInterpretation::implicit_srgb(icc).validate_with(Some(icc), ColorMode::Grayscale).is_err());
        assert!(old.document().working_profile_interpretation.validate_with(Some(icc), ColorMode::Rgb).is_err());
        assert!(crate::WorkingProfileInterpretation::ImplicitSGray { icc_blake3: "bad".into() }.validate_with(Some(icc), ColorMode::Grayscale).is_err());
        // Marker API identity is not generated CMS equality and is not claimed
        // to be an L1 metadata/Move semantic-profile preflight.
        for defect in 0..3 {
            let mut bad = transfer_owner(sample, encoding, precision);
            let id = bad.document().layers[0].id;
            let doc = &mut Arc::get_mut(&mut bad.owner).unwrap().document;
            let item = doc.xcf_state.as_mut().unwrap().items.iter_mut().find(|v| v.item == ItemRef::Layer(id)).unwrap();
            match defect {
                0 => item.name = "divergent".into(),
                1 => item.visible = false,
                _ => item.raster_bounds = None,
            }
            let before = bad.quota().usage().unwrap();
            for request in [
                AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None },
                AccountedEdit::LayerMetadata { layer: id, name: Some("original layer"), visible: Some(true), opacity: Some(1.0) },
            ] {
                assert!(bad.try_edit(request, &ctl()).is_err());
            }
            assert!(bad.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).is_err());
            assert_eq!(bad.quota().usage().unwrap(), before);
        }
    }
}
#[test]
#[ignore = "UNRUN four-role real quota/work/allocation-stage cancel and flat codec lifetime"]
fn transfer_paid_failures_and_copy_lifetime_do_not_add_model_chains() {
    for (sample, encoding, precision) in roles() {
        let old = transfer_owner(sample, encoding, precision);
        let id = old.document().layers[0].id;
        let q = old.quota().clone();
        let before = q.usage().unwrap();
        let index = q.reserve(QuotaKind::Index, (16 << 20) - before.index).unwrap();
        assert!(old.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).unwrap().shares_model(&old));
        assert!(old.try_edit(AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None }, &ctl()).unwrap().shares_model(&old));
        assert!(old.try_with_document_name("changed", &ctl()).is_err());
        drop(index);
        let deny = ReadControl { interrupt: &Interrupt::NONE, work: &|_| Err(BackingError::Work) };
        assert!(old.try_with_readonly_point_layer_translation(id, 1, 0, &deny).is_err());
        let allocated = || q.usage().unwrap().index > before.index;
        let stop = Interrupt::cancel_only(&allocated);
        assert!(old.try_with_document_name("changed", &ReadControl { interrupt: &stop, work: &|_| Ok(()) }).is_err());
        assert_eq!(q.usage().unwrap(), before);
        let first = old.try_with_readonly_point_layer_translation(id, 1, -1, &ctl()).unwrap();
        let weak = Arc::downgrade(&first.owner);
        let last = first.try_with_document_name("Gray transfer continued", &ctl()).unwrap();
        same_custody(&old, &last);
        assert!(last.owner.retention.downcast_ref::<OriginalRetention>().unwrap().original.shares_model(&old));
        drop(first);
        assert!(weak.upgrade().is_none());
        assert!(last.try_edit(AccountedEdit::LayerVisibility { layer: id, visible: false }, &ctl()).is_err());
        assert!(last.try_replace_selection(None, &ctl()).is_err());
        drop(old);
        drop(last);
        assert_eq!(q.usage().unwrap(), Default::default());
    }
}
