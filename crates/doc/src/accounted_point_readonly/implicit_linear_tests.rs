#[ignore = "UNRUN marker identity rejection separate from canonical map copy preflight"]
fn malformed_marker_is_not_a_profile_grant_and_canonical_repairs_refuse() {
    for sample in [SampleType::F32, SampleType::F64] {
        let old = owner(sample);
        let bytes = old.document().icc_profile.as_ref().unwrap();
        for marker in [
            crate::WorkingProfileInterpretation::ImplicitSrgb { icc_blake3: "0".repeat(64) },
            crate::WorkingProfileInterpretation::ImplicitSrgb { icc_blake3: "malformed".into() },
            crate::WorkingProfileInterpretation::implicit_sgray(bytes),
        ] {
            assert!(marker.validate_with(Some(bytes), ColorMode::Rgb).is_err());
        }
        // L1 custody does not establish CMS generated effective-profile equality.
        // Marker identity is checked by its separate API and full compositor.
        for visibility in [false, true] {
            let mut bad = owner(sample);
            let id = bad.document().layers[0].id;
            let state = Arc::get_mut(&mut bad.owner).unwrap().document.xcf_state.as_mut().unwrap();
            let item = state.items.iter_mut().find(|v| v.item == ItemRef::Layer(id)).unwrap();
            if visibility {
                item.visible = false;
            } else {
                item.name = "divergent".into();
            }
            let before = bad.quota().usage().unwrap();
            for request in [
                AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None },
                AccountedEdit::LayerMetadata { layer: id, name: Some("original layer"), visible: Some(true), opacity: Some(1.0) },
            ] {
                assert!(bad.try_edit(request, &ctl()).is_err());
            }
            assert!(bad.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).is_err());
            assert_eq!(bad.quota().usage().unwrap(), before);
        }
        let mut bad = owner(sample);
        let id = bad.document().layers[0].id;
        Arc::get_mut(&mut bad.owner)
            .unwrap()
            .document
            .xcf_state
            .as_mut()
            .unwrap()
            .items
            .iter_mut()
            .find(|v| v.item == ItemRef::Layer(id))
            .unwrap()
            .raster_bounds = None;
        assert!(bad.try_edit(AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None }, &ctl()).is_err());
        assert!(bad.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).is_err());
    }
}
#[test]
#[ignore = "UNRUN real quota/work/cancel and flat original retention through Linear copies"]
fn failures_refund_and_noop_or_repeated_copies_keep_actual_paid_owners() {
    for sample in [SampleType::F32, SampleType::F64] {
        let old = owner(sample);
        let id = old.document().layers[0].id;
        let q = old.quota().clone();
        let before = q.usage().unwrap();
        let blocker = q.reserve(QuotaKind::Index, (16 << 20) - before.index).unwrap();
        assert!(old.try_with_readonly_point_layer_translation(id, 0, 0, &ctl()).unwrap().shares_model(&old));
        assert!(old.try_edit(AccountedEdit::LayerMetadata { layer: id, name: None, visible: None, opacity: None }, &ctl()).unwrap().shares_model(&old));
        assert!(old.try_with_document_name("changed", &ctl()).is_err());
        drop(blocker);
        let deny = ReadControl { interrupt: &Interrupt::NONE, work: &|_| Err(BackingError::Work) };
        assert!(old.try_with_readonly_point_layer_translation(id, 1, 0, &deny).is_err());
        let allocated = || q.usage().unwrap().index > before.index;
        let stop = Interrupt::cancel_only(&allocated);
        assert!(old.try_with_document_name("changed", &ReadControl { interrupt: &stop, work: &|_| Ok(()) }).is_err());
        assert_eq!(q.usage().unwrap(), before);
        let first = old.try_with_readonly_point_layer_translation(id, 1, 0, &ctl()).unwrap();
        let weak = Arc::downgrade(&first.owner);
        let last = first.try_with_document_name("continued Linear", &ctl()).unwrap();
        same_custody(&old, &last);
        let root = last.owner.retention.downcast_ref::<OriginalRetention>().unwrap();
        assert!(root.original.shares_model(&old));
        drop(first);
        assert!(weak.upgrade().is_none());
        drop(old);
        drop(last);
        assert_eq!(q.usage().unwrap(), Default::default());
    }
}
