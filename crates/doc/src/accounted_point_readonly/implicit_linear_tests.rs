#[ignore = "UNRUN compound metadata and fixed-root Move preserve Linear native/profile/mask data"]
fn compound_and_move_copy_do_not_narrow_or_reinterpret_linear_native_words() {
    for sample in [SampleType::F32, SampleType::F64] {
        let mut old = owner(sample);
        let words: Vec<u8> = [-0.0f64, -0.125, 1.25, 0.5]
            .into_iter()
            .flat_map(|v| if sample == SampleType::F32 { (v as f32).to_ne_bytes().to_vec() } else { v.to_ne_bytes().to_vec() })
            .collect();
        // Actual same-q native COW charges include the16/32-byte pixel tile;
        // source fixture receipts do not substitute for these backing fees.
        let next = leaf(&old).try_edited_native(Rect::new(0, 14, 1, 15), &words, &ctl()).unwrap();
        Arc::get_mut(&mut old.owner).unwrap().document.layers[0].content = LayerContent::BackedRaster(next);
        let id = old.document().layers[0].id;
        let named =
            old.try_edit(AccountedEdit::LayerMetadata { layer: id, name: Some(" Linear 名 "), visible: Some(false), opacity: Some(-0.0) }, &ctl()).unwrap();
        let moved = named.try_with_readonly_point_layer_translation(id, -257, 259, &ctl()).unwrap();
        same_custody(&old, &moved);
        assert_eq!(raw(&moved, -257, 273), words);
        assert_eq!(raw(&old, 0, 14), words);
        assert_eq!(moved.document().layers[0].opacity.to_bits(), (-0f32).to_bits());
        let state = moved.document().xcf_state.as_ref().unwrap();
        let item = state.items.iter().find(|v| v.item == ItemRef::Layer(id)).unwrap();
        assert_eq!(item.name, " Linear 名 ");
        assert!(!item.visible);
        assert_eq!(item.raster_bounds, Some(leaf(&moved).operative_bounds()));
        assert!(moved.try_edit(AccountedEdit::LayerVisibility { layer: id, visible: false }, &ctl()).is_err());
        assert!(moved.try_replace_selection(None, &ctl()).is_err());
    }
}
